func runHotspareHook(command []string, spare string, config hotspareConfig, branch string) error {
	if len(command) == 0 {
		return nil
	}
	cmd := exec.Command(command[0], command[1:]...)
	cmd.Dir = spare
	cmd.Env = append(os.Environ(),
		"WORKDECK_SPARE="+spare,
		"WORKDECK_MAIN="+config.Main,
		"WORKDECK_BRANCH="+branch,
		"WORKDECK_BASE="+config.Base,
	)
	cmd.Stdin = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("hook %q: %w", command[0], err)
	}
	return nil
}

func claimHotspare(main, branch string) error {
	config, err := loadConfig(main)
	if err != nil {
		return err
	}
	if strings.TrimSpace(branch) == "" || strings.HasPrefix(branch, "-") {
		return errors.New("invalid branch name")
	}
	if _, err := git(config.Main, "check-ref-format", "--branch", branch); err != nil {
		return fmt.Errorf("invalid branch %q", branch)
	}
	if _, err := git(config.Main, "fetch", "origin"); err != nil {
		return err
	}
	if gitOK(config.Main, "show-ref", "--verify", "--quiet", "refs/remotes/origin/"+branch) {
		return fmt.Errorf("branch %s already exists on origin", branch)
	}
	for _, path := range append([]string{config.Main}, config.Spares...) {
		current, err := git(path, "branch", "--show-current")
		if err == nil && current == branch {
			return fmt.Errorf("branch %s is checked out at %s", branch, path)
		}
	}
	baseCommit, err := git(config.Main, "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	var blocked []string
	for _, spare := range config.Spares {
		if _, err := git(spare, "fetch", "origin"); err != nil {
			blocked = append(blocked, spare+": fetch failed")
			continue
		}
		if reason, ok := available(spare, config); !ok {
			blocked = append(blocked, spare+": "+reason)
			continue
		}
		lock, err := lockPath(spare)
		if err != nil {
			return err
		}
		file, err := os.OpenFile(lock, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if errors.Is(err, os.ErrExist) {
			blocked = append(blocked, spare+": locked")
			continue
		}
		if err != nil {
			return err
		}
		file.Close()
		if _, err := git(spare, "checkout", "-b", branch, baseCommit); err != nil {
			os.Remove(lock)
			return err
		}
		host, _ := os.Hostname()
		statePath, err := statePath(spare)
		if err != nil {
			return err
		}
		state := hotspareState{Claimed: true, Branch: branch, Base: config.Base, BaseCommit: baseCommit, ClaimedAt: time.Now().UTC(), Host: host, PID: os.Getpid()}
		if err := writeJSON(statePath, state); err != nil {
			return err
		}
		if err := runHotspareHook(config.OnClaim, spare, config, branch); err != nil {
			return err
		}
		fmt.Println(spare)
		return nil
	}
	return fmt.Errorf("no hotspare available; %s", strings.Join(blocked, "; "))
}

func selectSpare(config hotspareConfig, value string) (string, error) {
	for _, spare := range config.Spares {
		if value == spare || value == filepath.Base(spare) {
			return spare, nil
		}
	}
	return "", fmt.Errorf("not a configured hotspare: %s", value)
}

func releaseHotspare(main, value string, force bool) error {
	config, err := loadConfig(main)
	if err != nil {
		return err
	}
	spare, err := selectSpare(config, value)
	if err != nil {
		return err
	}
	state, err := loadState(spare)
	if err != nil {
		return err
	}
	if !state.Claimed {
		return fmt.Errorf("%s is not claimed", spare)
	}
	status, err := git(spare, "status", "--porcelain", "--ignore-submodules=none", "--untracked-files=all")
	if err != nil {
		return err
	}
	if status != "" && !force {
		return fmt.Errorf("%s has uncommitted changes:\n%s\nconfirm discarding these changes, then retry release with --force", spare, status)
	}
	if _, err := git(spare, "fetch", "origin"); err != nil {
		return err
	}
	// Release is the user's declaration that work is done. Keep local branches,
	// but do not require them to be published, merged, or match the claim name.
	if force {
		if _, err := git(spare, "reset", "--hard", "--recurse-submodules", "HEAD"); err != nil {
			return err
		}
		if _, err := git(spare, "clean", "-fd"); err != nil {
			return err
		}
		if _, err := git(spare, "submodule", "foreach", "--recursive", "git clean -fd"); err != nil {
			return err
		}
	}
	if _, err := git(spare, "checkout", localBase(config.Base)); err != nil {
		return err
	}
	if _, err := git(spare, "merge", "--ff-only", config.Base); err != nil {
		return err
	}
	if _, err := git(spare, "submodule", "update", "--init", "--recursive"); err != nil {
		return err
	}
	status, err = git(spare, "status", "--porcelain", "--ignore-submodules=none", "--untracked-files=all")
	if err != nil {
		return err
	}
	if status != "" {
		return fmt.Errorf("%s still has uncommitted changes after release cleanup:\n%s", spare, status)
	}
	if err := runHotspareHook(config.OnRelease, spare, config, state.Branch); err != nil {
		return err
	}
	statePath, err := statePath(spare)
	if err != nil {
		return err
	}
	lock, err := lockPath(spare)
	if err != nil {
		return err
	}
	if err := os.Remove(statePath); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.Remove(lock); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return writeJSON(statePath, hotspareState{Base: config.Base})
}

// pauseHotspare archives branch commits and tracked devtool changes, then
// returns the spare to base without requiring the branch to be pushed or merged.
// Other untracked files are discarded as part of freeing the spare.
func pauseHotspare(main, value string) error {
	config, err := loadConfig(main)
	if err != nil {
		return err
	}
	spare, err := selectSpare(config, value)
	if err != nil {
		return err
	}
	state, err := loadState(spare)
	if err != nil {
		return err
	}
	if !state.Claimed {
		return fmt.Errorf("%s is not claimed", spare)
	}
	if !gitOK(spare, "diff", "--quiet") || !gitOK(spare, "diff", "--cached", "--quiet") {
		return fmt.Errorf("%s has tracked uncommitted changes; commit them before pausing", spare)
	}
	patch, err := git(spare, "format-patch", "--binary", "--full-index", "--no-stat", "--stdout", state.BaseCommit+".."+state.Branch)
	if err != nil {
		return err
	}
	dir, err := pausedPath(config.Main)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0700); err != nil {
		return err
	}
	now := time.Now().UTC()
	digest := sha256.Sum256([]byte(state.Branch + "\x00" + now.Format(time.RFC3339Nano)))
	name := now.Format("20060102T150405Z") + "-" + hex.EncodeToString(digest[:6])
	patchPath := filepath.Join(dir, name+".patch")
	if err := os.WriteFile(patchPath, []byte(patch), 0600); err != nil {
		return err
	}
	devtoolPatches, err := archiveDevtoolPatches(spare, dir, name)
	if err != nil {
		return err
	}
	item := pausedHotspare{Branch: state.Branch, Base: config.Base, BaseCommit: state.BaseCommit, PausedAt: now, Patch: patchPath, DevtoolPatches: devtoolPatches}
	if err := writeJSON(filepath.Join(dir, name+".json"), item); err != nil {
		return err
	}
	if _, err := git(spare, "clean", "-fd"); err != nil {
		return err
	}
	if err := runAresDevtoolReset(spare, devtoolPatches); err != nil {
		return err
	}
	if _, err := git(spare, "fetch", "origin"); err != nil {
		return err
	}
	if _, err := git(spare, "checkout", localBase(config.Base)); err != nil {
		return err
	}
	if _, err := git(spare, "merge", "--ff-only", config.Base); err != nil {
		return err
	}
	if _, err := git(spare, "branch", "-D", state.Branch); err != nil {
		return err
	}
	if err := runHotspareHook(config.OnRelease, spare, config, state.Branch); err != nil {
		return err
	}
	stateFile, err := statePath(spare)
	if err != nil {
		return err
	}
	lock, err := lockPath(spare)
	if err != nil {
		return err
	}
	if err := os.Remove(stateFile); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.Remove(lock); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := writeJSON(stateFile, hotspareState{Base: config.Base}); err != nil {
		return err
	}
	fmt.Println(patchPath)
	return nil
}

func resumeHotspare(main, branch string) error {
	config, err := loadConfig(main)
	if err != nil {
		return err
	}
	if _, err := git(config.Main, "check-ref-format", "--branch", branch); err != nil {
		return fmt.Errorf("invalid branch %q", branch)
	}
	paused, err := pausedHotspareByBranch(config.Main, branch)
	if err != nil {
		return err
	}
	if _, err := os.Stat(paused.Patch); err != nil {
		return fmt.Errorf("paused branch patch %s: %w", paused.Patch, err)
	}
	for _, patch := range paused.DevtoolPatches {
		if _, err := os.Stat(patch.Patch); err != nil {
			return fmt.Errorf("paused devtool patch %s: %w", patch.Patch, err)
		}
	}
	for _, path := range append([]string{config.Main}, config.Spares...) {
		current, err := git(path, "branch", "--show-current")
		if err == nil && current == branch {
			return fmt.Errorf("branch %s is checked out at %s", branch, path)
		}
	}
	var blocked []string
	for _, spare := range config.Spares {
		if _, err := git(spare, "fetch", "origin"); err != nil {
			blocked = append(blocked, spare+": fetch failed")
			continue
		}
		if reason, ok := available(spare, config); !ok {
			blocked = append(blocked, spare+": "+reason)
			continue
		}
		lock, err := lockPath(spare)
		if err != nil {
			return err
		}
		file, err := os.OpenFile(lock, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if errors.Is(err, os.ErrExist) {
			blocked = append(blocked, spare+": locked")
			continue
		}
		if err != nil {
			return err
		}
		file.Close()
		if _, err := git(spare, "checkout", "-b", branch, paused.BaseCommit); err != nil {
			os.Remove(lock)
			blocked = append(blocked, spare+": cannot recreate branch")
			continue
		}
		stateFile, err := statePath(spare)
		if err != nil {
			return err
		}
		host, _ := os.Hostname()
		state := hotspareState{Claimed: true, Branch: branch, Base: config.Base, BaseCommit: paused.BaseCommit, ClaimedAt: time.Now().UTC(), Host: host, PID: os.Getpid()}
		if err := writeJSON(stateFile, state); err != nil {
			return err
		}
		if _, err := git(spare, "am", paused.Patch); err != nil {
			return fmt.Errorf("restore branch patch in %s: %w", spare, err)
		}
		if err := runAresDevtoolModify(spare, paused.DevtoolPatches); err != nil {
			return err
		}
		if err := runHotspareHook(config.OnClaim, spare, config, branch); err != nil {
			return err
		}
		fmt.Println(spare)
		return nil
	}
	return fmt.Errorf("no hotspare available; %s", strings.Join(blocked, "; "))
}

