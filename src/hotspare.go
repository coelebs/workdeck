const hotspareFile = "workdeck-hotspare.json"
const hotspareLock = "workdeck-hotspare.lock"
const pausedHotspareDir = "workdeck-paused"
const skillMarker = "<!-- Generated by workdeck; do not edit. -->"

type hotspareConfig struct {
	Main      string   `json:"main"`
	Spares    []string `json:"spares"`
	Base      string   `json:"base"`
	OnClaim   []string `json:"onClaim,omitempty"`
	OnRelease []string `json:"onRelease,omitempty"`
}

type hotspareState struct {
	Claimed    bool      `json:"claimed"`
	Branch     string    `json:"branch,omitempty"`
	Base       string    `json:"base"`
	BaseCommit string    `json:"baseCommit,omitempty"`
	ClaimedAt  time.Time `json:"claimedAt,omitempty"`
	Host       string    `json:"host,omitempty"`
	PID        int       `json:"pid,omitempty"`
}

type pausedHotspare struct {
	Branch         string         `json:"branch"`
	Base           string         `json:"base"`
	BaseCommit     string         `json:"baseCommit"`
	PausedAt       time.Time      `json:"pausedAt"`
	Patch          string         `json:"patch"`
	DevtoolPatches []devtoolPatch `json:"devtoolPatches,omitempty"`
}

type devtoolPatch struct {
	Source string `json:"source"`
	Patch  string `json:"patch"`
}

func canonicalDir(path string) (string, error) {
	path, err := filepath.Abs(path)
	if err != nil {
		return "", err
	}
	path, err = filepath.EvalSymlinks(path)
	if err != nil {
		return "", err
	}
	info, err := os.Stat(path)
	if err != nil {
		return "", err
	}
	if !info.IsDir() {
		return "", fmt.Errorf("not a directory: %s", path)
	}
	return path, nil
}

func gitDir(path string) (string, error) {
	info, err := os.Stat(filepath.Join(path, ".git"))
	if err != nil {
		return "", fmt.Errorf("%s is not an independent Git checkout: %w", path, err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("%s must have a .git directory, not a linked worktree", path)
	}
	return filepath.Join(path, ".git"), nil
}

func git(path string, args ...string) (string, error) {
	cmd := exec.Command("git", append([]string{"-C", path}, args...)...)
	output, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("git -C %s %s: %w: %s", path, strings.Join(args, " "), err, strings.TrimSpace(string(output)))
	}
	return strings.TrimSpace(string(output)), nil
}

func gitOK(path string, args ...string) bool {
	cmd := exec.Command("git", append([]string{"-C", path}, args...)...)
	return cmd.Run() == nil
}

func readJSON(path string, value any) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(data, value)
}

func writeJSON(path string, value any) error {
	data, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return os.WriteFile(path, data, 0600)
}

func configPath(main string) (string, error) {
	d, err := gitDir(main)
	return filepath.Join(d, hotspareFile), err
}
func statePath(spare string) (string, error) {
	d, err := gitDir(spare)
	return filepath.Join(d, hotspareFile), err
}
func lockPath(spare string) (string, error) {
	d, err := gitDir(spare)
	return filepath.Join(d, hotspareLock), err
}

func pausedPath(main string) (string, error) {
	d, err := gitDir(main)
	if err != nil {
		return "", err
	}
	return filepath.Join(d, pausedHotspareDir), nil
}

func loadConfig(main string) (hotspareConfig, error) {
	main, err := canonicalDir(main)
	if err != nil {
		return hotspareConfig{}, err
	}
	path, err := configPath(main)
	if err != nil {
		return hotspareConfig{}, err
	}
	var config hotspareConfig
	if err := readJSON(path, &config); err != nil {
		return hotspareConfig{}, fmt.Errorf("read hotspare config: %w", err)
	}
	if config.Main != main {
		return hotspareConfig{}, fmt.Errorf("hotspare config does not belong to %s", main)
	}
	return config, nil
}

func loadState(spare string) (hotspareState, error) {
	path, err := statePath(spare)
	if err != nil {
		return hotspareState{}, err
	}
	var state hotspareState
	if err := readJSON(path, &state); err != nil {
		return hotspareState{}, err
	}
	return state, nil
}

func localBase(base string) string {
	return strings.TrimPrefix(base, "origin/")
}

func (a app) hotspare(args []string) error {
	if len(args) == 0 {
		return errors.New("usage: workdeck hostspare setup [--base <ref>] <main> <spare>... | status --main <main> | claim --main <main> <branch> | release --main <main> <spare> [--force] | pause --main <main> <spare> | resume --main <main> <branch> | recover --main <main> <spare> --force | hook <set|clear> --main <main> <--claim|--release> [command args...]")
	}
	if args[0] == "--help" || args[0] == "-h" {
		fmt.Println("usage: workdeck hostspare setup [--base <ref>] <main> <spare>... | status --main <main> | claim --main <main> <branch> | release --main <main> <spare> [--force] | pause --main <main> <spare> | resume --main <main> <branch> | recover --main <main> <spare> --force | hook <set|clear> --main <main> <--claim|--release> [command args...]")
		return nil
	}
	switch args[0] {
	case "setup":
		return a.setupHotspares(args[1:])
	case "status":
		main, rest, err := mainFlag(args[1:])
		if err != nil {
			return err
		}
		if len(rest) != 0 {
			return errors.New("status accepts only --main")
		}
		return printHotspareStatus(main)
	case "claim":
		main, rest, err := mainFlag(args[1:])
		if err != nil {
			return err
		}
		if len(rest) != 1 {
			return errors.New("usage: workdeck hostspare claim --main <main> <branch>")
		}
		return claimHotspare(main, rest[0])
	case "release":
		main, rest, err := mainFlag(args[1:])
		if err != nil {
			return err
		}
		force := false
		var values []string
		for _, arg := range rest {
			if arg == "--force" && !force {
				force = true
			} else {
				values = append(values, arg)
			}
		}
		if len(values) != 1 || strings.HasPrefix(values[0], "-") {
			return errors.New("usage: workdeck hostspare release --main <main> <spare> [--force]")
		}
		return releaseHotspare(main, values[0], force)
	case "pause":
		main, rest, err := mainFlag(args[1:])
		if err != nil {
			return err
		}
		if len(rest) != 1 {
			return errors.New("usage: workdeck hostspare pause --main <main> <spare>")
		}
		return pauseHotspare(main, rest[0])
	case "resume":
		main, rest, err := mainFlag(args[1:])
		if err != nil {
			return err
		}
		if len(rest) != 1 {
			return errors.New("usage: workdeck hostspare resume --main <main> <paused branch>")
		}
		return resumeHotspare(main, rest[0])
	case "recover":
		main, rest, err := mainFlag(args[1:])
		if err != nil {
			return err
		}
		if len(rest) != 2 || rest[1] != "--force" {
			return errors.New("usage: workdeck hostspare recover --main <main> <spare> --force")
		}
		return recoverHotspare(main, rest[0])
	case "hook":
		return configureHotspareHook(args[1:])
	default:
		return fmt.Errorf("unknown hotspare command %q", args[0])
	}
}

func configureHotspareHook(args []string) error {
	if len(args) < 4 || (args[0] != "set" && args[0] != "clear") {
		return errors.New("usage: workdeck hostspare hook <set|clear> --main <main> <--claim|--release> [command args...]")
	}
	action := args[0]
	main, rest, err := mainFlag(args[1:])
	if err != nil {
		return err
	}
	if len(rest) == 0 || (rest[0] != "--claim" && rest[0] != "--release") {
		return errors.New("hook requires --claim or --release")
	}
	if action == "set" && len(rest) < 2 {
		return errors.New("hook set requires a command")
	}
	if action == "clear" && len(rest) != 1 {
		return errors.New("hook clear accepts only --claim or --release")
	}
	config, err := loadConfig(main)
	if err != nil {
		return err
	}
	if rest[0] == "--claim" {
		config.OnClaim = rest[1:]
	} else {
		config.OnRelease = rest[1:]
	}
	path, err := configPath(config.Main)
	if err != nil {
		return err
	}
	return writeJSON(path, config)
}

func mainFlag(args []string) (string, []string, error) {
	if len(args) < 2 || args[0] != "--main" {
		return "", nil, errors.New("--main <path> is required")
	}
	return args[1], args[2:], nil
}

func (a app) setupHotspares(args []string) error {
	base := ""
	if len(args) >= 2 && args[0] == "--base" {
		base, args = args[1], args[2:]
	}
	if len(args) < 2 {
		return errors.New("usage: workdeck hotspare setup [--base <ref>] <main> <spare>...")
	}
	main, err := canonicalDir(args[0])
	if err != nil {
		return err
	}
	if _, err := gitDir(main); err != nil {
		return err
	}
	branch, err := git(main, "branch", "--show-current")
	if err != nil {
		return err
	}
	if base == "" {
		if branch != "master" {
			return errors.New("--base is required when main is not on master")
		}
		base = "origin/master"
	}
	origin, err := git(main, "remote", "get-url", "origin")
	if err != nil {
		return err
	}
	config := hotspareConfig{Main: main, Base: base}
	seen := map[string]bool{main: true}
	for _, raw := range args[1:] {
		spare, err := canonicalDir(raw)
		if err != nil {
			return err
		}
		if seen[spare] {
			return fmt.Errorf("duplicate hotspare: %s", spare)
		}
		seen[spare] = true
		if _, err := gitDir(spare); err != nil {
			return err
		}
		spareOrigin, err := git(spare, "remote", "get-url", "origin")
		if err != nil {
			return err
		}
		if spareOrigin != origin {
			return fmt.Errorf("%s origin differs from main", spare)
		}
		status, err := git(spare, "status", "--porcelain")
		if err != nil {
			return err
		}
		if status != "" {
			return fmt.Errorf("%s has uncommitted changes", spare)
		}
		config.Spares = append(config.Spares, spare)
	}
	if existing, err := loadConfig(main); err == nil {
		config.OnClaim = existing.OnClaim
		config.OnRelease = existing.OnRelease
		requested := map[string]bool{}
		for _, spare := range config.Spares {
			requested[spare] = true
		}
		for _, spare := range existing.Spares {
			if requested[spare] {
				continue
			}
			state, stateErr := loadState(spare)
			if stateErr != nil {
				return fmt.Errorf("cannot remove configured hotspare %s: %w", spare, stateErr)
			}
			if state.Claimed {
				return fmt.Errorf("refusing to remove claimed hotspare %s", spare)
			}
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := a.checkSkillOverwrite(main, false); err != nil {
		return err
	}
	path, err := configPath(main)
	if err != nil {
		return err
	}
	if err := writeJSON(path, config); err != nil {
		return err
	}
	for _, spare := range config.Spares {
		statePath, err := statePath(spare)
		if err != nil {
			return err
		}
		state := hotspareState{Base: base}
		if old, err := loadState(spare); err == nil && old.Claimed {
			state = old
			state.Base = base
		}
		if err := writeJSON(statePath, state); err != nil {
			return fmt.Errorf("wrote main config but could not write %s: %w", spare, err)
		}
	}
	return a.installSkill(main, false)
}

func available(spare string, config hotspareConfig) (string, bool) {
	state, err := loadState(spare)
	if err != nil {
		return err.Error(), false
	}
	if state.Claimed {
		return "claimed: " + state.Branch, false
	}
	lock, err := lockPath(spare)
	if err != nil {
		return err.Error(), false
	}
	if _, err := os.Stat(lock); err == nil {
		return "locked", false
	}
	status, err := git(spare, "status", "--porcelain")
	if err != nil || status != "" {
		return "dirty", false
	}
	branch, err := git(spare, "branch", "--show-current")
	if err != nil || branch != localBase(config.Base) {
		return "not on " + localBase(config.Base), false
	}
	baseCommit, err := git(spare, "rev-parse", config.Base)
	if err != nil {
		return "cannot resolve " + config.Base, false
	}
	head, err := git(spare, "rev-parse", "HEAD")
	if err != nil || head != baseCommit {
		return "not aligned with " + config.Base, false
	}
	return "available", true
}

func printHotspareStatus(main string) error {
	config, err := loadConfig(main)
	if err != nil {
		return err
	}
	for _, spare := range config.Spares {
		reason, _ := available(spare, config)
		fmt.Printf("%s: %s\n", spare, reason)
	}
	paused, err := pausedHotspares(config.Main)
	if err != nil {
		return err
	}
	for _, paused := range paused {
		fmt.Printf("paused: %s (%s)\n", paused.Branch, paused.Patch)
		for _, devtool := range paused.DevtoolPatches {
			fmt.Printf("paused devtool: %s (%s)\n", devtool.Source, devtool.Patch)
		}
	}
	return nil
}

func pausedHotspares(main string) ([]pausedHotspare, error) {
	dir, err := pausedPath(main)
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var paused []pausedHotspare
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		var item pausedHotspare
		if err := readJSON(filepath.Join(dir, entry.Name()), &item); err != nil {
			return nil, err
		}
		paused = append(paused, item)
	}
	sort.Slice(paused, func(i, j int) bool { return paused[i].PausedAt.After(paused[j].PausedAt) })
	return paused, nil
}

func devtoolWorkspace(spare string) string {
	return filepath.Join(spare, "work", "build", "workspace")
}

func archiveDevtoolPatches(spare, archiveDir, name string) ([]devtoolPatch, error) {
	sources := filepath.Join(devtoolWorkspace(spare), "sources")
	entries, err := os.ReadDir(sources)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var patches []devtoolPatch
	for _, entry := range entries {
		if !entry.IsDir() || !gitOK(filepath.Join(sources, entry.Name()), "rev-parse", "--is-inside-work-tree") {
			continue
		}
		source := filepath.Join(sources, entry.Name())
		patch, err := git(source, "diff", "--binary", "HEAD")
		if err != nil {
			return nil, err
		}
		if patch == "" {
			continue
		}
		path := filepath.Join(archiveDir, name+"-devtool-"+entry.Name()+".patch")
		if err := os.WriteFile(path, []byte(patch+"\n"), 0600); err != nil {
			return nil, err
		}
		patches = append(patches, devtoolPatch{Source: filepath.Join("work", "build", "workspace", "sources", entry.Name()), Patch: path})
	}
	return patches, nil
}

func pausedHotspareByBranch(main, branch string) (pausedHotspare, error) {
	paused, err := pausedHotspares(main)
	if err != nil {
		return pausedHotspare{}, err
	}
	var matches []pausedHotspare
	for _, item := range paused {
		if item.Branch == branch {
			matches = append(matches, item)
		}
	}
	if len(matches) == 0 {
		return pausedHotspare{}, fmt.Errorf("no paused branch named %s", branch)
	}
	if len(matches) > 1 {
		return pausedHotspare{}, fmt.Errorf("multiple paused branches named %s; remove older archives before resuming", branch)
	}
	return matches[0], nil
}

func runAresDevtoolModify(spare string, patches []devtoolPatch) error {
	if len(patches) == 0 {
		return nil
	}
	var commands strings.Builder
	for _, patch := range patches {
		recipe := filepath.Base(patch.Source)
		if strings.Trim(recipe, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-+_.") != "" {
			return fmt.Errorf("unsafe devtool recipe name %q", recipe)
		}
		fmt.Fprintf(&commands, "devtool modify %s\n", recipe)
	}
	commands.WriteString("exit\n")
	cmd := exec.Command("script", "-qef", "-c", "./ares-build-agent/run-build-agent.py", "/dev/null")
	cmd.Dir = spare
	cmd.Stdin = strings.NewReader(commands.String())
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("recreate devtool workspace: %w", err)
	}
	for _, patch := range patches {
		source := filepath.Join(spare, patch.Source)
		if _, err := git(source, "apply", "--binary", patch.Patch); err != nil {
			return fmt.Errorf("restore devtool patch %s: %w", patch.Patch, err)
		}
	}
	return nil
}

