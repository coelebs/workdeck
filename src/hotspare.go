func activeHotspares(projects []entry) ([]entry, error) {
	var configs []hotspareConfig
	for _, project := range projects {
		path, err := configPath(project.path)
		if err != nil {
			continue
		}
		var config hotspareConfig
		if err := readJSON(path, &config); errors.Is(err, os.ErrNotExist) {
			continue
		} else if err != nil {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		if config.Main == project.path {
			configs = append(configs, config)
		}
	}
	spares := map[string]bool{}
	var active []entry
	for _, config := range configs {
		for _, spare := range config.Spares {
			spares[spare] = true
			state, err := loadState(spare)
			if err != nil {
				return nil, err
			}
			if state.Claimed {
				active = append(active, entry{kind: "hotspare", name: filepath.Base(spare) + " [" + state.Branch + "]", path: spare})
			}
		}
	}
	var filtered []entry
	for _, project := range projects {
		if !spares[project.path] {
			filtered = append(filtered, project)
		}
	}
	sort.Slice(active, func(i, j int) bool { return active[i].path > active[j].path })
	return append(filtered, active...), nil
}

func (a app) skill(args []string) error {
	if len(args) == 0 || args[0] != "install" {
		return errors.New("usage: workdeck skill install --main <main> [--force]")
	}
	main, rest, err := mainFlag(args[1:])
	if err != nil {
		return err
	}
	force := len(rest) == 1 && rest[0] == "--force"
	if len(rest) != 0 && !force {
		return errors.New("usage: workdeck skill install --main <main> [--force]")
	}
	return a.installSkill(main, force)
}

func (a app) installSkill(main string, force bool) error {
	config, err := loadConfig(main)
	if err != nil {
		return err
	}
	if err := a.checkSkillOverwrite(config.Main, force); err != nil {
		return err
	}
	path := a.skillPath(config.Main)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	name := "workdeck-" + filepath.Base(config.Main)
	digest := sha256.Sum256([]byte(config.Main))
	content := fmt.Sprintf("---\nname: %s\ndescription: Use when investigating or editing the managed %s repository. Investigate in main; claim a hostspare before editing unless already in a claimed spare.\n---\n\n%s\n# Workdeck hostspares: %s\n\nInvestigate and plan in `%s`. Before any edit, check whether the current directory is already a claimed hostspare:\n\n```sh\nworkdeck hostspare status --main %s\n```\n\nIf the current directory is listed as claimed, work there and do not claim another spare. Otherwise, claim a spare:\n\n```sh\nworkdeck hostspare claim --main %s <branch>\n```\n\nWork only in the claimed path. If claiming fails, report the unavailable spares and wait. Do not edit the main checkout.\n\nWhen the user says work is done or asks to free the spare, trust that decision. Do not require push or merge verification. Release with:\n\n```sh\nworkdeck hostspare release --main %s <spare>\n```\n\nIf release reports uncommitted changes, inspect and summarize staged, unstaged, untracked, and submodule changes. Ask for explicit confirmation before discarding them; saying the work is done alone is not consent to discard changes. Only after confirmation, retry with:\n\n```sh\nworkdeck hostspare release --main %s <spare> --force\n```\n\nForce discards tracked changes and non-ignored untracked files, including inside initialized submodules. It preserves local branches, ignored build output, and untracked nested repositories. If cleanup still fails, report the blocker; do not broaden deletion. Never push as part of releasing.\n\nTo pause committed work for later, archive it and free the spare:\n\n```sh\nworkdeck hostspare pause --main %s <spare>\n```\n\nManaged-set id: %s\n", name, filepath.Base(config.Main), skillMarker, filepath.Base(config.Main), config.Main, config.Main, config.Main, config.Main, config.Main, config.Main, hex.EncodeToString(digest[:8]))
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		return err
	}
	return a.copyOpenCodeSkill(name, path, force)
}

func (a app) skillPath(main string) string {
	name := "workdeck-" + filepath.Base(main)
	return filepath.Join(a.home, ".agents", "skills", name, "SKILL.md")
}

func (a app) openCodeSkillPath(main string) string {
	name := "workdeck-" + filepath.Base(main)
	return filepath.Join(a.home, ".config", "opencode", "skills", name, "SKILL.md")
}

// OpenCode v1 only scans ~/.config/opencode/skills and ignores symlinked skill
// files. Newer OpenCode versions also scan ~/.agents/skills, so maintain a
// generated copy for v1 alongside the universal source.
func (a app) copyOpenCodeSkill(name, source string, force bool) error {
	path := filepath.Join(a.home, ".config", "opencode", "skills", name, "SKILL.md")
	info, err := os.Lstat(path)
	if err == nil {
		generated := false
		if info.Mode()&os.ModeSymlink == 0 {
			if content, readErr := os.ReadFile(path); readErr != nil {
				return readErr
			} else {
				generated = strings.Contains(string(content), skillMarker)
			}
		}
		if !generated && !force {
			return fmt.Errorf("refusing to overwrite existing OpenCode skill %s; use workdeck skill install --main <main> --force", path)
		}
		if err := os.Remove(path); err != nil {
			return err
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	content, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	return os.WriteFile(path, content, 0644)
}

func (a app) checkSkillOverwrite(main string, force bool) error {
	path := a.skillPath(main)
	if old, err := os.ReadFile(path); err == nil && !strings.Contains(string(old), skillMarker) && !force {
		return fmt.Errorf("refusing to overwrite manually changed skill %s; use workdeck skill install --main %s --force", path, main)
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	openCodePath := a.openCodeSkillPath(main)
	if info, err := os.Lstat(openCodePath); err == nil && info.Mode()&os.ModeSymlink == 0 && !force {
		content, readErr := os.ReadFile(openCodePath)
		if readErr != nil {
			return readErr
		}
		if !strings.Contains(string(content), skillMarker) {
			return fmt.Errorf("refusing to overwrite existing OpenCode skill %s; use workdeck skill install --main %s --force", openCodePath, main)
		}
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}
